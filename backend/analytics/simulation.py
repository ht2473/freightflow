"""Имитационная модель загруженности улично-дорожной сети.

Данных о загруженности дорог Москвы в открытом доступе не существует: ЦОДД
открытого потока не публикует, служба дорожной обстановки Яндекса платная,
ЭРА-ГЛОНАСС закрыта. Система не может получить эти сведения и не делает вида,
что получает.

Вместо этого загруженность рассчитывается моделью по величинам, которые
система действительно измеряет: классу магистрали, числу полос, разрешённой
скорости, положению относительно зон ограничения и плотности размещения
логистических объектов поблизости. Результат помечается как смоделированный
и таким доходит до пользователя — в карточке, в отчёте и в выгрузке.

Модель воспроизводит четыре наблюдаемых свойства городского движения:

1. **суточный профиль** — два пика, утренний и вечерний, с провалом ночью;
2. **недельный профиль** — рабочие дни нагруженнее выходных;
3. **радиальный градиент** — к центру плотность движения растёт;
4. **влияние грузогенерирующих объектов** — вблизи складских комплексов
   доля грузового движения выше, а с ней и загруженность.

Все коэффициенты вынесены в именованные постоянные с обоснованием: модель
должна читаться и оспариваться, а не приниматься на веру.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import datetime

from core.choices import RoadClass

#: Базовая загруженность по классу магистрали, баллы шкалы 0—10.
#:
#: Значения отражают проектную пропускную способность: дорога с изолированным
#: движением при равной нагрузке заторится позже улицы с регулируемыми
#: пересечениями.
BASE_BY_CLASS: dict[str, float] = {
    RoadClass.HIGHWAY: 3.0,
    RoadClass.ARTERIAL: 4.0,
    RoadClass.COLLECTOR: 5.0,
}

#: Суточный профиль: множитель нагрузки по часам от полуночи до 23 часов.
#:
#: Форма профиля — два пика с провалом ночью — устойчиво воспроизводится
#: в исследованиях городского движения. Утренний пик острее вечернего:
#: прибытие на работу сосредоточено в узком окне, тогда как убытие
#: растянуто. Значения нормированы так, что среднесуточный множитель
#: близок к единице.
HOURLY_PROFILE: tuple[float, ...] = (
    0.25, 0.18, 0.15, 0.15, 0.20, 0.35,   # 00—05
    0.65, 1.15, 1.60, 1.55, 1.25, 1.10,   # 06—11
    1.05, 1.05, 1.05, 1.15, 1.35, 1.60,   # 12—17
    1.55, 1.30, 1.00, 0.75, 0.55, 0.38,   # 18—23
)

#: Недельный профиль: множитель по дням недели, понедельник первым.
#:
#: Пятница нагруженнее прочих рабочих дней, воскресенье — наименее
#: нагруженный день.
WEEKLY_PROFILE: tuple[float, ...] = (1.00, 1.02, 1.03, 1.04, 1.12, 0.78, 0.68)

#: Надбавка за положение внутри зоны ограничения, баллы.
#:
#: Отражает радиальный градиент плотности движения: чем ближе к центру,
#: тем выше нагрузка на сеть при той же пропускной способности.
ZONE_SURCHARGE: dict[str, float] = {"sk": 1.6, "ttk": 1.0, "mkad": 0.4}

#: Надбавка за грузогенерирующее окружение, баллы на один объект
#: в пятикилометровой полосе, с насыщением.
FREIGHT_SURCHARGE_PER_OBJECT = 0.02
FREIGHT_SURCHARGE_CAP = 1.5

#: Скидка за число полос сверх четырёх, баллы на полосу.
#: Дополнительная полоса повышает пропускную способность, но с убывающей
#: отдачей, поэтому эффект ограничен.
LANE_RELIEF_PER_LANE = 0.25
LANE_RELIEF_CAP = 1.0

#: Границы шкалы загруженности.
SCALE_MIN, SCALE_MAX = 0, 10

#: Доля разрешённой скорости, сохраняющаяся при полном заторе.
#: Движение при девяти-десяти баллах не прекращается полностью, но
#: замедляется примерно до десятой части разрешённой скорости.
MIN_SPEED_RATIO = 0.10


@dataclass(frozen=True)
class RoadContext:
    """Сведения о магистрали, существенные для расчёта загруженности.

    Атрибуты:
        road_class: класс магистрали;
        lanes: число полос; ``None`` — не размечено;
        speed_limit_kmh: разрешённая скорость; ``None`` — не размечена;
        innermost_zone: код самой внутренней зоны, которую пересекает
            магистраль, либо ``None``;
        freight_objects_nearby: число логистических объектов поблизости.
    """

    road_class: str
    lanes: int | None = None
    speed_limit_kmh: int | None = None
    innermost_zone: str | None = None
    freight_objects_nearby: int = 0


@dataclass(frozen=True)
class Estimate:
    """Расчётная оценка обстановки на участке."""

    congestion_level: int
    avg_speed_kmh: float | None
    components: dict[str, float]

    @property
    def explanation(self) -> str:
        """Разложение оценки по составляющим — для карточки участка."""
        parts = [f"{name}: {value:+.2f}" for name, value in self.components.items()]
        return "; ".join(parts)


def hourly_factor(moment: datetime) -> float:
    """Множитель нагрузки для момента времени.

    Момент должен быть выражен в местном времени: пики движения привязаны
    к распорядку дня города, а не к всемирному координированному времени.
    Хранятся отметки времени в UTC, поэтому вызывающий код обязан выполнить
    перевод — иначе профиль окажется сдвинутым на разницу часовых поясов.
    """
    return HOURLY_PROFILE[moment.hour] * WEEKLY_PROFILE[moment.weekday()]


def estimate(context: RoadContext, moment: datetime) -> Estimate:
    """Рассчитать загруженность участка и скорость потока.

    Расчёт ведётся сложением поправок к базовому уровню класса магистрали.
    Аддитивная форма выбрана намеренно: вклад каждой составляющей виден
    в отдельности и может быть оспорен, тогда как произведение
    коэффициентов такой возможности не оставляет.
    """
    components: dict[str, float] = {}

    base = BASE_BY_CLASS.get(context.road_class, BASE_BY_CLASS[RoadClass.COLLECTOR])
    components["класс магистрали"] = base

    factor = hourly_factor(moment)
    # Суточный и недельный профили действуют на базовый уровень, а не на
    # сумму: ночью пустеет сама магистраль, а не её окружение.
    timed = base * factor
    components["время суток и день недели"] = timed - base

    zone_surcharge = ZONE_SURCHARGE.get(context.innermost_zone or "", 0.0)
    components["положение в городе"] = zone_surcharge

    freight = min(
        context.freight_objects_nearby * FREIGHT_SURCHARGE_PER_OBJECT,
        FREIGHT_SURCHARGE_CAP,
    )
    components["грузогенерирующее окружение"] = freight

    relief = 0.0
    if context.lanes and context.lanes > 4:
        relief = -min((context.lanes - 4) * LANE_RELIEF_PER_LANE, LANE_RELIEF_CAP)
    components["число полос"] = relief

    raw = timed + zone_surcharge + freight + relief
    level = int(round(max(SCALE_MIN, min(SCALE_MAX, raw))))

    return Estimate(
        congestion_level=level,
        avg_speed_kmh=_speed_from_level(level, context.speed_limit_kmh),
        components=components,
    )


def _speed_from_level(level: int, speed_limit_kmh: int | None) -> float | None:
    """Скорость потока при заданной загруженности.

    Зависимость нелинейная: первые баллы загруженности почти не сказываются
    на скорости, а последние снижают её резко. Форма задана косинусом,
    убывающим от разрешённой скорости до её десятой части.
    """
    if not speed_limit_kmh:
        return None

    share = level / SCALE_MAX
    ratio = MIN_SPEED_RATIO + (1.0 - MIN_SPEED_RATIO) * (math.cos(math.pi * share) + 1) / 2
    return round(speed_limit_kmh * ratio, 1)
