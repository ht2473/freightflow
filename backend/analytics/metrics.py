#: Полный реестр показателей.
REGISTRY: tuple[Metric, ...] = _OWN + _from_components()

#: Показатель по его обозначению.
BY_KEY: dict[str, Metric] = {item.key: item for item in REGISTRY}


def describe(key: str) -> Metric | None:
    """Описание показателя по обозначению."""
    return BY_KEY.get(key)


def by_section() -> list[dict]:
    """Реестр, разложенный по разделам, — для страницы методики."""
    grouped = []
    for code, title in SECTIONS:
        items = [item for item in REGISTRY if item.section == code]
        if items:
            grouped.append({"code": code, "title": title, "metrics": items})
    return grouped


