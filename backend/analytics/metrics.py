@dataclass(frozen=True)
class Metric:
    """Описание показателя, достаточное для его проверки."""

    key: str
    title: str
    unit: str
    formula: str
    meaning: str
    origin: str
    source: str
    #: Раздел, к которому показатель относится: порядок вывода в методике.
    section: str = ""

    @property
    def origin_label(self) -> str:
        """Подпись происхождения величины для маркера в интерфейсе."""
        return DataOrigin(self.origin).label


