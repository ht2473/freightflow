"""Запросы к Overpass API на языке Overpass QL.

Запросы вынесены в отдельный модуль по двум причинам. Во-первых, текст запроса
служит ключом кеша, поэтому его правка должна быть заметным изменением, а не
побочным следствием правки загрузчика. Во-вторых, состав выгрузки — предмет
методики, а не техники: по этим текстам видно, что именно система считает
логистической инфраструктурой Москвы.

Область поиска задаётся границей субъекта федерации (``admin_level=4``).
Она включает присоединённые в 2012 году территории, где расположена
значительная часть современных складских комплексов.

Выгрузка всюду завершается ``out geom``. Форма ``out tags geom`` выглядит
уместнее, но подавляет состав отношения: у площадных объектов, размеченных
отношением, не окажется участков контура, и площадь останется неизвестной.
"""

from __future__ import annotations

#: Объявление области поиска. Помещается в начало каждого запроса.
AREA = 'area["name"="Москва"]["admin_level"="4"]->.searchArea;'

#: Габаритный прямоугольник Москвы с запасом. Применяется там, где поиск
#: по области невозможен: границы округов сами являются отношениями и
#: в область по определению не входят.
BBOX = "55.1,36.7,56.1,38.0"


#: Кандидаты в реестр объектов инфраструктуры.
#:
#: Выгрузка намеренно шире итогового реестра: разметка сообщества неоднородна,
#: и один и тот же склад может быть обозначен как здание, как территория или
#: как точка. Отбор выполняется правилами :mod:`etl.osm.classify`, а не самим
#: запросом — так решение об отнесении объекта остаётся прослеживаемым.
INFRASTRUCTURE = f"""[out:json][timeout:600];
{AREA}
(
  nwr["building"="warehouse"](area.searchArea);
  nwr["landuse"="logistics"](area.searchArea);
  nwr["industrial"](area.searchArea);
  nwr["shop"="storage_rental"](area.searchArea);
  nwr["amenity"="loading_dock"](area.searchArea);
  nwr["amenity"="weighbridge"](area.searchArea);
  nwr["amenity"="parking"]["hgv"](area.searchArea);
  nwr["parking"="truck"](area.searchArea);
  nwr["railway"="yard"](area.searchArea);
  nwr["landuse"="railway"]["name"](area.searchArea);
  nwr["landuse"="industrial"]["name"](area.searchArea);
);
out geom;"""


#: Границы административных округов Москвы.
#:
#: Уровень 5 соответствует административному округу. Поиск ведётся по
#: габаритному прямоугольнику, а не по области: искомые отношения сами
#: задают границы и в область по определению не попадают.
DISTRICTS = f"""[out:json][timeout:600];
relation["boundary"="administrative"]["admin_level"="5"]({BBOX});
out geom;"""


#: Магистральная улично-дорожная сеть.
#:
#: Отбираются классы, по которым в действительности идёт грузовое движение:
#: скоростные дороги, магистрали и улицы общегородского значения. Улицы
#: районного значения и внутриквартальные проезды в сеть не входят —
#: движение грузового транспорта по ним ограничено.
ROAD_NETWORK = f"""[out:json][timeout:900];
{AREA}
(
  way["highway"~"^(motorway|trunk|primary)$"](area.searchArea);
);
out geom;"""


#: Кольцевые магистрали, задающие зоны ограничения движения грузового
#: транспорта: МКАД, Третье транспортное кольцо, Садовое кольцо.
#:
#: Постановление Правительства Москвы № 379 от 22.08.2011 определяет зоны
#: именно через эти магистрали, поэтому их геометрия является первичной:
#: границы зон строятся из неё, а не задаются отдельно.
RING_ROADS = f"""[out:json][timeout:600];
(
  relation["type"="route"]["route"="road"]["name"="Садовое кольцо"]({BBOX});
  relation["type"="route"]["route"="road"]["name"="Третье транспортное кольцо"]({BBOX});
  way["highway"]["ref"="МКАД"]({BBOX});
  way["highway"]["name"="Московская кольцевая автомобильная дорога"]({BBOX});
);
out geom;"""


#: Федеральные автомобильные коридоры, входящие в город.
#:
#: Внешние грузовые потоки приходят в Москву по вылетным магистралям,
#: продолжающим федеральные трассы. Отношение маршрута описывает трассу
#: целиком, поэтому выгрузка ограничивается пределами города.
FREIGHT_CORRIDORS = f"""[out:json][timeout:600];
relation["type"="route"]["route"="road"]["ref"~"^(М|А|E)"]({BBOX});
out tags;"""
