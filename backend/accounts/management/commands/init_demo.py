class Command(BaseCommand):
    """Наполнить систему демонстрационными данными."""

    help = "Создание демонстрационных пользователей, материалов и обращений"

    def add_arguments(self, parser) -> None:
        parser.add_argument(
            "--password",
            type=str,
            default=DEMO_PASSWORD,
            help="Пароль демонстрационных учётных записей",
        )
        parser.add_argument(
            "--skip-users",
            action="store_true",
            help="Не создавать демонстрационные учётные записи",
        )

    @transaction.atomic
    def handle(self, *args, **options) -> None:
        self.stdout.write(self.style.MIGRATE_HEADING("Демонстрационное наполнение"))

        if not options["skip_users"]:
            self._create_users(options["password"])
        self._create_categories()
        self._create_articles()
        self._create_static_pages()
        self._create_feedback()
        self._create_cabinet_content()

        self.stdout.write("")
        self.stdout.write(self.style.SUCCESS("Демонстрационные данные подготовлены"))
        if not options["skip_users"]:
            self.stdout.write("")
            self.stdout.write("  Учётные записи для демонстрации:")
            for username, role, *_ in DEMO_USERS:
                label = dict(Role.choices)[role]
                self.stdout.write(f"    {username:<10} {label:<16} пароль: {options['password']}")

    # ------------------------------------------------------------ пользователи

    def _create_users(self, password: str) -> None:
        """Создать учётные записи всех ролей."""
        created = 0
        for username, role, first, last, organization, position in DEMO_USERS:
            user, is_new = User.objects.get_or_create(
                username=username,
                defaults={
                    "first_name": first,
                    "last_name": last,
                    "email": f"{username}@freightflow.local",
                    "is_staff": role == Role.ADMIN,
                    "is_superuser": role == Role.ADMIN,
                },
            )
            if is_new:
                user.set_password(password)
                user.save()
                created += 1

            profile, _ = UserProfile.objects.get_or_create(user=user)
            profile.role = role
            profile.organization = organization
            profile.position = position
            profile.save(update_fields=["role", "organization", "position", "updated_at"])

            group = Group.objects.filter(name=f"role:{role}").first()
            if group:
                user.groups.add(group)

        self.stdout.write(f"  Учётные записи: создано {created}, всего {len(DEMO_USERS)}")

    # ---------------------------------------------------------------- материалы

    def _create_categories(self) -> None:
        """Создать рубрики аналитических материалов."""
        for code, name, description, order in CATEGORIES:
            ArticleCategory.objects.get_or_create(
                code=code,
                defaults={"name": name, "description": description, "order": order},
            )
        self.stdout.write(f"  Рубрики материалов: {ArticleCategory.objects.count()}")

    def _create_articles(self) -> None:
        """Опубликовать демонстрационные аналитические материалы."""
        author = User.objects.filter(username="admin").first()
        now = timezone.now()

        for offset, (category_code, slug, title, lead, body, featured) in enumerate(ARTICLES):
            category = ArticleCategory.objects.filter(code=category_code).first()
            if category is None:
                continue
            Article.objects.get_or_create(
                slug=slug,
                defaults={
                    "category": category,
                    "title": title,
                    "lead": lead,
                    "body": body,
                    "author": author,
                    "is_featured": featured,
                    "published_at": now - timedelta(days=offset * 6 + 2),
                    "reading_minutes": max(3, len(body) // 900),
                    "view_count": 180 - offset * 17,
                },
            )
        self.stdout.write(f"  Аналитические материалы: {Article.objects.count()}")

    def _create_static_pages(self) -> None:
        """Создать редактируемые информационные страницы."""
        for code, title, lead, body in STATIC_PAGES:
            StaticPage.objects.get_or_create(
                code=code, defaults={"title": title, "lead": lead, "body": body}
            )
        self.stdout.write(f"  Информационные страницы: {StaticPage.objects.count()}")

    # --------------------------------------------------------------- обращения

    def _create_feedback(self) -> None:
        """Создать примеры обращений в разных состояниях."""
        admin = User.objects.filter(username="admin").first()
        now = timezone.now()

        for offset, (name, email, organization, topic, message, status, answer) in enumerate(
            FEEDBACK
        ):
            entry, created = FeedbackMessage.objects.get_or_create(
                email=email,
                topic=topic,
                defaults={
                    "name": name,
                    "organization": organization,
                    "message": message,
                    "status": status,
                    "answer": answer,
                    "answered_by": admin if answer else None,
                    "answered_at": now - timedelta(days=offset) if answer else None,
                },
            )
            if created and offset:
                # Разносим обращения по времени, чтобы журнал выглядел
                # правдоподобно при демонстрации.
                FeedbackMessage.objects.filter(pk=entry.pk).update(
                    created_at=now - timedelta(days=offset * 3, hours=offset * 5)
                )
        self.stdout.write(f"  Обращения: {FeedbackMessage.objects.count()}")

    # ----------------------------------------------------------- личные кабинеты

    def _create_cabinet_content(self) -> None:
        """Наполнить личные кабинеты демонстрационных пользователей."""
        analyst = User.objects.filter(username="analyst").first()
        operator = User.objects.filter(username="operator").first()
        if not analyst:
            return

        objects = list(InfrastructureObject.objects.select_related("district")[:4])
        districts = list(District.objects.all()[:3])

        for obj in objects:
            Favorite.objects.get_or_create(
                user=analyst,
                kind=Favorite.Kind.OBJECT,
                target_id=obj.pk,
                defaults={"title": obj.name, "note": f"Округ: {obj.district.short_name}"},
            )
        for district in districts:
            Favorite.objects.get_or_create(
                user=analyst,
                kind=Favorite.Kind.DISTRICT,
                target_id=district.pk,
                defaults={"title": district.name},
            )

        SavedView.objects.get_or_create(
            user=analyst,
            title="Крупные склады южных округов",
            defaults={
                "page": "core:object_list",
                "query": "district=6&sort=capacity",
                "description": "Объекты ЮАО в порядке убывания мощности хранения",
            },
        )
        SavedView.objects.get_or_create(
            user=analyst,
            title="Открытые инциденты на грузовых направлениях",
            defaults={
                "page": "core:incident_list",
                "query": "state=open&cargo=1&severity=3",
                "description": "Контроль событий, влияющих на прохождение грузового транспорта",
            },
        )

        if districts:
            ComparisonSet.objects.get_or_create(
                user=analyst,
                title="Сравнение южных и северных округов",
                defaults={
                    "kind": ComparisonSet.Kind.DISTRICT,
                    "members": ",".join(str(d.pk) for d in districts),
                },
            )

        if operator:
            subscription, _created = IncidentSubscription.objects.get_or_create(
                user=operator,
                district=districts[0] if districts else None,
                defaults={"min_severity": 3, "cargo_only": True},
            )
            self._deliver_pending(subscription)

        self.stdout.write(
            f"  Содержимое кабинетов: закладок {Favorite.objects.count()}, "
            f"сохранённых видов {SavedView.objects.count()}"
        )

    def _deliver_pending(self, subscription) -> None:
        """Показать в кабинете подписки то, что она уже отбирает.

        Уведомление не сочиняется: оно составляется по событиям, которые
        действительно есть в базе и подпадают под условия подписки. Пустая
        база оставляет раздел пустым, и это верно — оповещать не о чем.
        """
        if Notification.objects.filter(user=subscription.user).exists():
            return
        events = TrafficIncident.objects.open().select_related("district", "road")[:200]
        delivered = notify.incidents_loaded(list(events))
        if delivered:
            self.stdout.write(f"  Уведомления по подпискам: {delivered}")


